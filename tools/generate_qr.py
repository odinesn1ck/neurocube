"""Regenerate static GitHub QR matrix with qrcode==8.2; not required to build firmware."""
from pathlib import Path
import qrcode
qr=qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M,box_size=1,border=4)
qr.add_data('https://github.com/odinesn1ck/neurocube')
qr.make(fit=True)
matrix=qr.get_matrix()
assert len(matrix)<=41
rows=[sum((1<<x) for x,dark in enumerate(row) if dark) for row in matrix]
text='#pragma once\n#include <cstdint>\n// Generated by tools/generate_qr.py (qrcode 8.2), including four-module quiet zone.\n'
text+='// Payload: https://github.com/odinesn1ck/neurocube\n'
text+=f'inline constexpr int qr_size={len(matrix)};\ninline constexpr uint64_t qr_rows[]={{'+','.join(hex(row)+'ULL' for row in rows)+'};\n'
Path(__file__).resolve().parents[1].joinpath('src/presentation/qr_data.hpp').write_text(text,encoding='utf-8')
print(f'Generated {len(matrix)}x{len(matrix)} QR matrix including quiet zone')
